"""Regenerate the skill tables in README.md, AGENTS.md and docs/.

Reads every plugins/*/skills/*/SKILL.md and plugin.json, then rewrites:
  - the block between <!-- skills:start --> and <!-- skills:end --> in
    README.md and AGENTS.md
  - docs/skills.md (one section per plugin, one entry per skill)
  - docs/scripts.md (every bundled script with the first line of its
    docstring or header comment)

Usage:
  python scripts/build_docs.py          rewrite the files
  python scripts/build_docs.py --check  exit 1 if any file is out of date

Standard library only.
"""

import argparse
import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START, END = "<!-- skills:start -->", "<!-- skills:end -->"
STATUS_TEXT = {
    "proven": "Proven on one machine",
    "assembled": "Assembled from proven parts, not run as a whole",
    "new": "New, not yet tested",
}
SCRIPT_SUFFIXES = {".py", ".ps1", ".js", ".sh", ".cmd"}


def frontmatter(path):
    text = path.read_text(encoding="utf-8")
    end = text.find("\n---", 3)
    block = text[3:end] if text.startswith("---") and end > 0 else ""
    data, key, nested = {}, None, None
    for line in block.splitlines():
        if not line.strip():
            continue
        if line[0] in " \t":
            sub = line.strip()
            if nested is not None and ":" in sub:
                k, _, v = sub.partition(":")
                data[nested][k.strip()] = v.strip().strip("\"'")
            elif key:
                data[key] = (data[key] + " " + sub).strip()
            continue
        key, _, value = line.partition(":")
        key, value = key.strip(), value.strip()
        nested = None
        if key == "metadata" and not value:
            data[key], nested = {}, key
            continue
        if value in (">", "|", ">-", "|-"):
            value = ""
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        data[key] = value
    return data


def collect():
    market = json.loads((ROOT / ".claude-plugin/marketplace.json")
                        .read_text(encoding="utf-8"))
    plugins = []
    for entry in market["plugins"]:
        folder = ROOT / entry["source"]
        skills = []
        for skill_md in sorted(folder.glob("skills/*/SKILL.md")):
            meta = frontmatter(skill_md)
            md = meta.get("metadata") or {}
            status = md.get("maturity") or md.get("status", "")
            skills.append({
                "name": meta.get("name", skill_md.parent.name),
                "description": meta.get("description", ""),
                "status": STATUS_TEXT.get(status, status or "Not set"),
                "path": skill_md.parent.relative_to(ROOT).as_posix(),
            })
        plugins.append({**entry, "folder": folder, "skills": skills})
    return plugins


def short(text, limit=160):
    text = re.sub(r"\s+", " ", text).strip()
    first = re.split(r"(?<=\.)\s", text)[0]
    if len(first) > limit:
        first = first[:limit].rsplit(" ", 1)[0] + " ..."
    return first


def table(plugins, link_prefix=""):
    rows = ["| Plugin | Skill | What it does | Alpha status |",
            "|---|---|---|---|"]
    for plugin in plugins:
        for skill in plugin["skills"]:
            link = f"[`{skill['name']}`]({link_prefix}{skill['path']})"
            rows.append(f"| `{plugin['name']}` | {link} | "
                        f"{short(skill['description'])} | "
                        f"{skill['status']} |")
    return "\n".join(rows)


def skills_page(plugins, base_url):
    out = ["---", "title: Skills", "---", "", "# Skills", "",
           "Generated by `scripts/build_docs.py` from each skill's "
           "`SKILL.md`.", ""]
    for plugin in plugins:
        out += [f"## {plugin['category']}: `{plugin['name']}`", "",
                plugin["description"], "",
                f"Install: `/plugin install {plugin['name']}@"
                "fde-spotfire-ai-skills`", ""]
        for skill in plugin["skills"]:
            out += [f"### `{skill['name']}`", "",
                    re.sub(r"\s+", " ", skill["description"]).strip(), "",
                    f"Alpha status: {skill['status']}. "
                    f"Source: [{skill['path']}]({base_url}{skill['path']})",
                    ""]
    return "\n".join(out)


def first_line(path):
    text = path.read_text(encoding="utf-8", errors="replace")
    if path.suffix == ".py":
        try:
            doc = ast.get_docstring(ast.parse(text))
        except SyntaxError:
            doc = None
        if doc:
            return doc.strip().splitlines()[0]
    for line in text.splitlines()[:15]:
        line = line.strip().lstrip("#/<>!*-").strip()
        if line and not line.lower().startswith(("usage", "requires",
                                                  "!/usr", "coding")):
            return line
    return ""


def scripts_page(plugins, base_url):
    out = ["---", "title: Bundled scripts", "---", "",
           "# Bundled scripts", "",
           "Every script the skills ship, with the first line of its own "
           "description. Generated by `scripts/build_docs.py`. Scripts "
           "write only into the folders you pass them or into "
           "`DXP_WORKSPACE`; see [SECURITY.md](" + base_url +
           "SECURITY.md).", ""]
    for plugin in plugins:
        for skill in plugin["skills"]:
            folder = ROOT / skill["path"]
            files = sorted(p for p in folder.rglob("*")
                           if p.suffix in SCRIPT_SUFFIXES and p.is_file()
                           and "__pycache__" not in p.parts
                           and "tests" not in p.parts
                           and not p.name.startswith("test_")
                           and "assets" not in p.parts
                           and "examples" not in p.parts)
            if not files:
                continue
            out += [f"## `{skill['name']}`", "",
                    "| Script | What it does |", "|---|---|"]
            for path in files:
                rel = path.relative_to(folder).as_posix()
                desc = first_line(path).replace("|", "\\|")
                out.append(f"| `{rel}` | {desc} |")
            out.append("")
    return "\n".join(out)


def replace_block(path, body):
    text = path.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit(f"{path.name}: markers missing")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n{body}\n{END}{tail}"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    plugins = collect()
    base = "https://github.com/josesilvestre-spotfire/" \
           "fde-spotfire-ai-skills/tree/main/"
    outputs = {
        ROOT / "README.md": replace_block(ROOT / "README.md",
                                          table(plugins)),
        ROOT / "AGENTS.md": replace_block(ROOT / "AGENTS.md",
                                          table(plugins)),
        ROOT / "docs/skills.md": skills_page(plugins, base) + "\n",
        ROOT / "docs/scripts.md": scripts_page(plugins, base) + "\n",
    }
    stale = []
    for path, text in outputs.items():
        old = path.read_text(encoding="utf-8") if path.exists() else ""
        if old != text:
            stale.append(path.relative_to(ROOT).as_posix())
            if not args.check:
                path.write_text(text, encoding="utf-8", newline="\n")
    if args.check and stale:
        print("out of date: " + ", ".join(stale))
        return 1
    print(("updated: " + ", ".join(stale)) if stale else "up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
